#!/usr/bin/env node
// Writes .claude/skills/README.md: the index of every project skill, generated from each SKILL.md.
//   node scripts/skills-index.mjs          write it
//   node scripts/skills-index.mjs --check  exit 1 if it is out of date
import { writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, read, exists } from './lib.mjs';

const GROUPS = [
  ['Work loop', ['prime', 'grill-with-docs', 'grilling', 'domain-modeling', 'slice-tickets', 'plan-ticket', 'tdd-workflow', 'implement-ticket', 'validate', 'review-changes', 'ship', 'rules-check-drift']],
  ['SNS documents and designs', ['sns-change-control', 'sns-change-request', 'sns-screen-update', 'sns-plate-component']],
  ['Engineering discipline', ['verification-before-completion', 'systematic-debugging', 'vercel-react-best-practices', 'impeccable', 'skill-creator']],
];
const dir = join(ROOT, '.claude/skills');
const all = readdirSync(dir).filter((d) => existsSync(join(dir, d, 'SKILL.md'))).sort();
const meta = (d) => {
  const fm = /^---\n([\s\S]*?)\n---/.exec(read(`.claude/skills/${d}/SKILL.md`))?.[1] ?? '';
  const desc = (/^description:\s*("?)([\s\S]*?)\1\s*$/m.exec(fm)?.[2] ?? '').replace(/\s+/g, ' ').trim();
  const user = /^disable-model-invocation:\s*true/m.test(fm) ? 'you (/' + d + ')' : 'you or the agent';
  const paths = /^paths:/m.test(fm) ? 'scoped' : '';
  const source = exists(`.claude/skills/${d}/LICENSE.txt`) || d === 'impeccable' ? 'adapted from open source (see its LICENSE.txt / SOURCE)' : 'SNS';
  return { desc: desc.length > 180 ? `${desc.slice(0, 177)}…` : desc, user, paths, source };
};
const placed = new Set(GROUPS.flatMap(([, l]) => l));
const groups = [...GROUPS, ['Other', all.filter((d) => !placed.has(d))]];
let md = '# Project skills\n\nGenerated by `node scripts/skills-index.mjs` from each `SKILL.md`. Do not edit by hand.\n\nSkills load only when their description matches the work, so they cost little context. How to write one: `AGENTS.md` in this folder.\n';
for (const [title, list] of groups) {
  const rows = list.filter((d) => all.includes(d));
  if (!rows.length) continue;
  md += `\n## ${title}\n\n| Skill | Started by | Use it for | Source |\n| --- | --- | --- | --- |\n`;
  for (const d of rows) { const m = meta(d); md += `| [${d}](${d}/SKILL.md) | ${m.user}${m.paths ? ', scoped to paths' : ''} | ${m.desc.replace(/\|/g, '\\|')} | ${m.source} |\n`; }
}
const target = '.claude/skills/README.md';
if (process.argv.includes('--check')) {
  if (!exists(target) || read(target) !== md) { console.error('Skills index is out of date. Run: node scripts/skills-index.mjs'); process.exit(1); }
  console.log('Skills index up to date.');
} else { writeFileSync(join(ROOT, target), md); console.log(`Wrote ${target} (${all.length} skills).`); }
