// Copies Plate from design-system/ (the master, rank 4) into the app: tokens, component styles, fonts, the logo and the line icons.
// The copies are git-ignored and made before dev, build, test, typecheck and lint, so the app can never drift from the design system.
// Every run also checks the tokens against design-system/tokens.json and fails when one is missing or different (TRD › Interface and languages).
// --check: copy nothing; fail when a copy is missing or differs. SYNC_PLATE_ROOT: write under another folder (tests).
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const app = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = process.env.SYNC_PLATE_ROOT || app;
const repo = join(app, '..');
const ds = join(repo, 'design-system');

function fail(message) {
  console.error(`sync-plate: ${message}`);
  process.exit(1);
}

// 1. Tokens: every value in tokens.json must be the value in tokens.css, the file the app uses.
const tokensCss = readFileSync(join(ds, 'tokens.css'), 'utf8');
const tokensJson = JSON.parse(readFileSync(join(ds, 'tokens.json'), 'utf8'));
const expected = [];
for (const group of ['color', 'spacing', 'radius', 'size', 'shadow']) {
  for (const t of tokensJson[group]?.tokens ?? []) expected.push([t.name, t.value]);
}
for (const [family, value] of Object.entries(tokensJson.type?.families ?? {})) expected.push([`font-${family}`, value]);
const actual = new Map([...tokensCss.matchAll(/--([\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
const wrong = expected.filter(([name, value]) => actual.get(name) !== value).map(([name, value]) => `--${name} should be ${value}, is ${actual.get(name) ?? 'missing'}`);
if (expected.length < 20) fail(`only ${expected.length} tokens read from tokens.json; its shape may have changed`);
if (wrong.length) fail(`design-system/tokens.css differs from tokens.json:\n  ${wrong.join('\n  ')}`);

// 2. Fonts named in fonts.css.
const fontsCss = readFileSync(join(ds, 'fonts.css'), 'utf8');
const fontFiles = [...fontsCss.matchAll(/url\(["']\.\.\/fonts\/([^"']+)["']\)/g)].map((m) => m[1]);
if (fontFiles.length === 0) fail('no font files found in design-system/fonts.css');

// 3. The line-icon drawings, taken from bundle.js (its `var P = { ... };` block), and their names as a type.
const bundleJs = readFileSync(join(ds, 'components/bundle.js'), 'utf8');
const iconBlock = /\n {2}var P = (\{[\s\S]*?\n {2}\});/.exec(bundleJs);
if (!iconBlock) fail('the icon block (var P = { ... }) was not found in design-system/components/bundle.js');
const iconNames = [...iconBlock[1].matchAll(/\n\s+(\w+): '/g)].map((m) => m[1]);
if (iconNames.length < 40) fail(`only ${iconNames.length} icons read from bundle.js; the icon block may be cut short`);
const iconsTs = `// Generated by scripts/sync-plate.mjs from design-system/components/bundle.js. Do not edit.
export type IconName = ${iconNames.map((n) => `'${n}'`).join(' | ')};
export const ICON_PATHS: Record<IconName, string> = ${iconBlock[1]};
`;

/** [target relative to the output root, content as a Buffer] */
const copies = [
  ['src/ui/plate/tokens.css', Buffer.from(tokensCss)],
  ['src/ui/plate/plate.css', Buffer.from(readFileSync(join(ds, 'components/bundle.css'), 'utf8').replace(/^@import [^\n]*\n/gm, ''))],
  ['src/ui/plate/icons.ts', Buffer.from(iconsTs)],
  ['src/ui/plate/fonts.css', Buffer.from(fontsCss.replace(/url\(["']\.\.\/fonts\//g, 'url("/plate/fonts/'))],
  ...fontFiles.map((f) => [`public/plate/fonts/${f}`, readFileSync(join(repo, 'fonts', f))]),
  ...['sns-logo.png', 'sns-logo-mark.png'].map((f) => [`public/plate/brand/${f}`, readFileSync(join(ds, 'assets/brand', f))]),
];

const check = process.argv.includes('--check');
const stale = [];
for (const [target, content] of copies) {
  const path = join(out, target);
  if (existsSync(path) && readFileSync(path).equals(content)) continue;
  if (check) stale.push(target);
  else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}
if (stale.length) fail(`the Plate copy differs from design-system/ (stale): ${stale.join(', ')}. Run: npm run sync:plate`);
