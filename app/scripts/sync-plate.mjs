// Copies Plate from design-system/ (the master, rank 4) into the app: tokens, component styles, fonts and the logo.
// The copies are git-ignored and made before dev, build, test and typecheck, so the app can never drift from the design system.
// --check: report and fail when a copy is missing or differs (TRD › Interface and languages).
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const app = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(app, '..');
const ds = join(repo, 'design-system');

const fontsCss = readFileSync(join(ds, 'fonts.css'), 'utf8');
const fontFiles = [...fontsCss.matchAll(/url\("\.\.\/fonts\/([^"]+)"\)/g)].map((m) => m[1]);

// The line-icon drawings, taken from bundle.js (its `var P = { ... };` block) so the app draws exactly the same icons.
const bundleJs = readFileSync(join(ds, 'components/bundle.js'), 'utf8');
const iconBlock = /\n  var P = (\{[\s\S]*?\n  \});/.exec(bundleJs);
if (!iconBlock) throw new Error('sync-plate: the icon block (var P = { ... }) was not found in design-system/components/bundle.js');
const iconsTs = `// Generated by scripts/sync-plate.mjs from design-system/components/bundle.js. Do not edit.\nexport const ICON_PATHS: Record<string, string> = ${iconBlock[1]};\n`;

/** [target relative to app/, content as a Buffer] */
const copies = [
  ['src/ui/plate/tokens.css', readFileSync(join(ds, 'tokens.css'))],
  ['src/ui/plate/plate.css', Buffer.from(readFileSync(join(ds, 'components/bundle.css'), 'utf8').replace(/^@import [^\n]*\n/gm, ''))],
  ['src/ui/plate/icons.ts', Buffer.from(iconsTs)],
  ['src/ui/plate/fonts.css', Buffer.from(fontsCss.replace(/url\("\.\.\/fonts\//g, 'url("/plate/fonts/'))],
  ...fontFiles.map((f) => [`public/plate/fonts/${f}`, readFileSync(join(repo, 'fonts', f))]),
  ...['sns-logo.png', 'sns-logo-mark.png'].map((f) => [`public/plate/brand/${f}`, readFileSync(join(ds, 'assets/brand', f))]),
];

const check = process.argv.includes('--check');
const stale = [];
for (const [target, content] of copies) {
  const path = join(app, target);
  const same = existsSync(path) && readFileSync(path).equals(content);
  if (same) continue;
  if (check) stale.push(target);
  else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}
if (stale.length) {
  console.error(`Plate copy differs from design-system/ (stale): ${stale.join(', ')}. Run: node scripts/sync-plate.mjs`);
  process.exit(1);
}
