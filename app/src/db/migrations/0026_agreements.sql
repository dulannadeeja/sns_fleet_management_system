-- An agreement wording version is never changed: the only change ever allowed is approving it once (system design 14).
CREATE FUNCTION agreement_wording_approve_once() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' OR OLD.approved_at IS NOT NULL
     OR (to_jsonb(NEW) - 'approved_at' - 'approved_by') IS DISTINCT FROM (to_jsonb(OLD) - 'approved_at' - 'approved_by') THEN
    RAISE EXCEPTION 'agreement_wording is insert-only: a version can only be approved once';
  END IF;
  RETURN NEW;
END $$;
